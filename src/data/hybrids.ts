export function getHybridsByCrop(crop: Crop): Hybrid[] {
  return hybrids.filter((h) => h.crop === crop);
}

export function getHybridBySlug(slug: string): Hybrid | undefined {
  return hybrids.find((h) => h.slug === slug);
}

export function minPrice(hybrid: Hybrid): number | undefined {
  if (!hybrid.priceTiers || hybrid.priceTiers.length === 0) return undefined;
  return Math.min(...hybrid.priceTiers.map((t) => t.price));
}
